async function call(method, p, body, key, env) {
  const url = new URL('http://x' + p);
  const req = new Request(url, { method, headers: Object.assign({ 'content-type': 'application/json' }, key === undefined ? { 'x-pf-key': KEY } : key ? { 'x-pf-key': key } : {}), body: body ? JSON.stringify(body) : undefined });
  const res = await H.handlePf(req, env || { DB, PF_KEY: KEY, DATA_GO_KR_KEY: 'k' }, url.pathname, url.searchParams);
  return { status: res.status, data: await res.json().catch(() => null) };
}
